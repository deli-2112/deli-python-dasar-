# Bab #3: Tipe Data Dasar Python

# 1. String (str) - Teks yang diapit tanda kutip
nama = "Deli"
jurusan = 'Rekayasa Perangkat Lunak'
print("Nama:", nama, "| Tipe:", type(nama))

# 2. Integer (int) - Bilangan bulat
umur = 16
print("Umur:", umur, "| Tipe:", type(umur))

# 3. Float (float) - Bilangan desimal
tinggi_badan = 168.5
print("Tinggi Badan:", tinggi_badan, "| Tipe:", type(tinggi_badan))

# 4. Complex (complex) - Bilangan kompleks (real + imajiner)
bilangan_kompleks = 3 + 4j
print("Bilangan Kompleks:", bilangan_kompleks, "| Tipe:", type(bilangan_kompleks))

# 5. Boolean (bool) - Nilai kebenaran (True atau False)
siswa_aktif = True
print("Status Aktif:", siswa_aktif, "| Tipe:", type(siswa_aktif))

# 6. NoneType (None) - Nilai kosong / belum diisi
data_kosong = None
print("Data Kospong:", data_kosong, "| Tipe:", type(data_kosong))